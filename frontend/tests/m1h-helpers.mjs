export const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

export async function waitFor(condition, ms = 2000, label = "condition") {
  const deadline = Date.now() + ms;
  while (!condition()) {
    if (Date.now() > deadline) throw new Error(`timed out waiting for ${label}`);
    await sleep(2);
  }
}

export function json(status, body, headers = {}) {
  return new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json", ...headers } });
}

// A controllable clock in seconds.
export function clock(start = 1_800_000_000) {
  let t = start;
  const now = () => t;
  now.advance = (seconds) => {
    t += seconds;
  };
  return now;
}

// A fake fetch that records calls and answers through `handler(url, init, index)`.
export function fakeFetch(handler) {
  const calls = [];
  const fn = async (url, init = {}) => {
    const call = { url: String(url), init, index: calls.length, headers: new Headers(init.headers ?? {}) };
    calls.push(call);
    return handler(call);
  };
  fn.calls = calls;
  return fn;
}

// Token endpoint that issues token-1, token-2, ... each valid for 600 s from `now`.
export function tokenEndpoint(now, options = {}) {
  let issued = 0;
  const handler = () => {
    issued += 1;
    if (options.fail) return options.fail(issued);
    return json(200, { token: `token-${issued}`, expires_at: Math.floor(now()) + 600 }, { "cache-control": "no-store" });
  };
  handler.issued = () => issued;
  return handler;
}

