// The OpenAPI document of the REAL FastAPI app (backend/main.py), generated by the backend's own code.
let cachedOpenApi;
export function backendOpenApi() {
  if (cachedOpenApi) return cachedOpenApi;
  const python = path.join(BACKEND, "venv", "Scripts", "python.exe");
  const unix = path.join(BACKEND, "venv", "bin", "python");
  const exe = process.platform === "win32" ? python : unix;
  const code = "import json, main; print(json.dumps(main.app.openapi()))";
  const result = spawnSync(exe, ["-c", code], {
    cwd: BACKEND,
    env: {
      ...process.env,
      PYTHONPATH: BACKEND,
      PYTHON_DOTENV_DISABLED: "1",
      PYTHONDONTWRITEBYTECODE: "1",
      APP_ENV: "test",
      GROQ_API_KEY: "test-only-not-a-real-key",
      DATABASE_URL: "sqlite:///m1h_contract_unused.db",
    },
    encoding: "utf8",
    timeout: 120000,
  });
  if (result.status !== 0) throw new Error(`could not read the backend OpenAPI: ${result.stderr.slice(-500)}`);
  cachedOpenApi = JSON.parse(result.stdout.trim().split("\n").pop());
  return cachedOpenApi;
}
